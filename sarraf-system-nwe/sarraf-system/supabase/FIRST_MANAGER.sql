-- ⚠️ پێش هەموو شتێک: ئیمەیلی ماناجەر ڕاست بکەوە
--
--    لە Supabase → Authentication → Users
--    manager@local.sarraf  →  manager@sarraf.local
--
--    ئەپەکە کاتێک «manager» دەنووسیت بەدوای manager@sarraf.local دەگەڕێت.
--    بە دۆمەینی پێچەوانەوە هەرگیز ناتوانیت بچیتە ژوورەوە.


-- ── دانانی هەر سێکیان ────────────────────────────────────────────────
--
-- ئەم UUID ـانە هی ئەکاونتەکانی خۆتن، لە Authentication ـەوە وەرگیراون.
-- ئەگەر ناو یان ژمارە بگۆڕیت، تەنها ئەو دەقانە بگۆڕە کە بە کوردی نووسراون.
--
-- `on conflict` واتا دووبارە ڕەنکردنی زیانی نییە — ئەگەر پێشتر دروستبووبن،
-- تەنها پلەکانیان ڕاست دەکاتەوە.

insert into public.app_users (id, auth_id, name, role, admin_level, phone, rate, scope_curs, deleted)
values
  -- ژمارەکان بۆ پەیوەندییە، نەک بۆ چوونەژوورەوە. ئەم سێ ئەکاونتە بە ناو
  -- دەچنە ژوورەوە (manager / sarkhel / admin). ژمارە ڕاستەقینەکان دابنێ،
  -- یان null بەجێیان بهێڵە.
  ('mgr-zeman', '1287d05b-c9b8-44ae-abe7-8bc739f158f3',
   'ماناجەر',  'admin', 'manager',  null, 0, '{}', false),

  ('own-zeman', '093de96c-ae18-4b14-bdf0-a762e4eec9f6',
   'سەرخێڵ',   'admin', 'owner',    null, 0, '{}', false),

  ('adm-zeman', 'b7ec5fa3-586f-4f8f-aca7-9ca936934b6a',
   'ئەدمین',   'admin', 'operator', null, 0, '{}', false)

on conflict (auth_id) do update
  set role        = excluded.role,
      admin_level = excluded.admin_level,
      name        = excluded.name,
      deleted     = false;


-- ── پشکنین ───────────────────────────────────────────────────────────
--
-- دەبێت سێ ڕیز ببینیت، بەم ڕیزبەندییە: manager، owner، operator.

select admin_level as "پلە", name as "ناو", id as "ژمارەی ناوخۆ"
from public.app_users
where role = 'admin' and not deleted
order by case admin_level when 'manager' then 0 when 'owner' then 1 else 2 end;


-- ════════════════════════════════════════════════════════════════════
-- چۆن بچیتە ژوورەوە
--
--   ماناجەر   →  manager   + وشەی نهێنییەکەی
--   سەرخێڵ    →  sarkhel   + وشەی نهێنییەکەی
--   ئەدمین    →  admin     + وشەی نهێنییەکەی
--
-- ژمارەی مۆبایل پێویست ناکات — ئەم سێ ئەکاونتە بە ناو دەچنە ژوورەوە.
-- بەکارهێنەرانی ئاسایی (کڕیار، هاوبەش) بە ژمارەی مۆبایل دەچنە ژوورەوە.
--
--
-- کێ چی دەتوانێت
--
--   ماناجەر   →  هەموو شتێک. گۆڕینی وشەی نهێنیی هەر کەسێک. دروستکردنی سەرخێڵ.
--   سەرخێڵ    →  کاروبارەکە. دروستکردنی ئەدمین. دەستی لە ماناجەر نادات.
--   ئەدمین    →  کاری ڕۆژانە. هیچ ئەکاونتێکی بەڕێوەبردن دروست ناکات.
--
--
-- ⚠️ دوایین ماناجەر ناتوانرێت لاببرێت.
--    ئەگەر دواتر ویستت ئەکاونتەکەت بگۆڕیت — سەرەتا ماناجەرێکی نوێ دابنێ،
--    پاشان کۆنەکە لاببە. سیستەمێک کە کەس پێی ناگات پاراستووتر نییە.
-- ════════════════════════════════════════════════════════════════════
