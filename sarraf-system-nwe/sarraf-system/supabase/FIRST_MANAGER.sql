-- دروستکردنی یەکەم ماناجەر — ئەکاونتی تۆ
--
-- ئەمە تەنها یەک جار ڕەن دەکرێت. دوای ئەوە هەموو شتێک لەناو ئەپەکەوە دەکرێت.
-- ════════════════════════════════════════════════════════════════════

-- ── هەنگاوی ١: ئەکاونتەکەت دروست بکە ─────────────────────────────────
--
-- لە Supabase → Authentication → Users → "Add user"
--   Email:    ژمارەی مۆبایلەکەت@sarraf.local     (بۆ نموونە 07501234567@sarraf.local)
--   Password: لانیکەم ١٢ پیت
--   ✅ "Auto Confirm User" هەڵبژێرە
--
-- پاشان UUID ـەکەی کۆپی بکە.


-- ── هەنگاوی ٢: ئەم دێڕە ڕەن بکە ──────────────────────────────────────
--
-- سێ شتەکە بگۆڕە: UUID، ناوەکەت، ژمارەکەت.
--
-- بۆچی ئەمە لێرە دەکرێت و لە ئەپەکەدا نا: هیچ کەس ناتوانێت پلەیەک بداتە خۆی.
-- یەکەم ماناجەر دەبێت لە دەرەوەی ئەپەکەوە دابنرێت، و هەبوونی وشەی نهێنیی
-- داتابەیس تاکە بەڵگەیە کە پێش هەبوونی ماناجەرێک بەردەستە.

insert into public.app_users (id, auth_id, name, role, admin_level, phone, rate, scope_curs, deleted)
values (
  'mgr-' || substr(md5(random()::text), 1, 12),
  'UUID-ـەکەی-هەنگاوی-١-لێرە-دابنێ'::uuid,
  'ناوی تۆ',
  'admin',
  'manager',
  '07501234567',
  0,
  '{}',
  false
);


-- ── هەنگاوی ٣: پشکنین ────────────────────────────────────────────────

select id, name, admin_level, phone
from public.app_users
where role = 'admin'
order by case admin_level when 'manager' then 0 when 'owner' then 1 else 2 end, name;


-- ════════════════════════════════════════════════════════════════════
-- دوای ئەمە
--
-- ١. لە ئەپەکەدا بچۆ ژوورەوە بە ژمارە و وشەی نهێنییەکەت
-- ٢. ئەکاونتی سەرخێڵ دروست بکە — پلە: owner
-- ٣. سەرخێڵ ئەدمینەکانی خۆی دروست دەکات — پلە: operator
--
--   ماناجەر   → هەموو شتێک. گۆڕینی وشەی نهێنیی هەر کەسێک. دروستکردنی سەرخێڵ.
--   سەرخێڵ    → کاروبارەکە. دروستکردنی ئەدمین. ناتوانێت دەستی لە ماناجەر بدات.
--   ئەدمین    → کاری ڕۆژانە. ناتوانێت هیچ ئەکاونتێکی بەڕێوەبردن دروست بکات.
--
-- ⚠️ دوایین ماناجەر ناتوانرێت لاببرێت. ئەگەر دەتەوێت ئەکاونتەکەت بگۆڕیت،
--    سەرەتا ماناجەرێکی نوێ دابنێ، پاشان کۆنەکە لاببە.
-- ════════════════════════════════════════════════════════════════════
